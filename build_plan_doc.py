def load_exemplars(doc):
    """从模板中抽取各类段落的样板元素。"""
    paras = doc.paragraphs
    picks = {}
    picks["cover"] = paras[0]._p
    for p in paras[1:]:
        t = p.text.strip()
        if not t:
            continue
        if t.startswith("一、") and "h1" not in picks:
            picks["h1"] = p._p
        elif t.startswith("1.1") and "h2" not in picks:
            picks["h2"] = p._p
        elif t.startswith("1.1.1") and "h3" not in picks:
            picks["h3"] = p._p
        elif t.startswith("\u201c") and "body" not in picks:
            picks["body"] = p._p
        elif t.startswith("技术性能维度评估指标表") and "caption" not in picks:
            picks["caption"] = p._p
    picks["table"] = doc.tables[0]._tbl
    return picks


def clone_para(proto, text):
    """深拷贝样板段落，只保留一个 run 并写入文字。"""
    el = copy.deepcopy(proto)
    # 去掉书签，避免重复 id
    for tag in ("w:bookmarkStart", "w:bookmarkEnd"):
        for node in el.findall(qn(tag)):
            el.remove(node)
    runs = el.findall(qn("w:r"))
    if not runs:
        raise RuntimeError("样板段落没有 run")
    first = runs[0]
    for r in runs[1:]:
        el.remove(r)
    # 清空 first 里的所有 w:t，只留一个
    for t in first.findall(qn("w:t")):
        first.remove(t)
    t = el.makeelement(qn("w:t"), {})
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    first.append(t)
    return el


def build_table(proto_tbl, rows, widths):
    """按 4 列模板生成表格，行列数与内容自定义。"""
    tbl = copy.deepcopy(proto_tbl)
    table = Table(tbl, None)
    # 统一到目标行数
    data_rows = [r for r in table.rows]
    proto_row = copy.deepcopy(data_rows[1]._tr)
    while len(table.rows) > 1:
        tbl.remove(table.rows[-1]._tr)
    while len(table.rows) < len(rows):
        tbl.append(copy.deepcopy(proto_row))
    table = Table(tbl, None)
    for ri, row_text in enumerate(rows):
        row = table.rows[ri]
        for ci, cell_text in enumerate(row_text):
            cell = row.cells[ci]
            # 只留一个段落、一个 run
            for extra in cell.paragraphs[1:]:
                extra._p.getparent().remove(extra._p)
            p = cell.paragraphs[0]
            for extra in p._p.findall(qn("w:r"))[1:]:
                p._p.remove(extra)
            run = p.runs[0] if p.runs else p.add_run()
            for t in run._element.findall(qn("w:t")):
                run._element.remove(t)
            run.text = cell_text
    # 调整列宽
    grid = tbl.find(qn("w:tblGrid"))
    for gc, w in zip(grid.findall(qn("w:gridCol")), widths):
        gc.set(qn("w:w"), str(w))
    for tr in tbl.findall(qn("w:tr")):
        for tc, w in zip(tr.findall(qn("w:tc")), widths):
            tcPr = tc.find(qn("w:tcPr"))
            if tcPr is not None:
                tcW = tcPr.find(qn("w:tcW"))
                if tcW is not None:
                    tcW.set(qn("w:w"), str(w))
    # 行属性：禁止跨页断行；首行作为表头跨页重复
    for idx, tr in enumerate(tbl.findall(qn("w:tr"))):
        trPr = tr.find(qn("w:trPr"))
        if trPr is None:
            trPr = tr.makeelement(qn("w:trPr"), {})
            tr.insert(0, trPr)
        if trPr.find(qn("w:cantSplit")) is None:
            trPr.append(trPr.makeelement(qn("w:cantSplit"), {}))
        if idx == 0 and trPr.find(qn("w:tblHeader")) is None:
            trPr.append(trPr.makeelement(qn("w:tblHeader"), {}))
    # 表头加粗，便于与正文区分
    first_row = Table(tbl, None).rows[0]
    for cell in first_row.cells:
        for p in cell.paragraphs:
            for r in p.runs:
                r.bold = True
    # 表内文字统一五号（10.5pt），避免 12pt 在窄列中过度折行
    rows_obj = Table(tbl, None).rows
    for row in rows_obj:
        for cell in row.cells:
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(10.5)
    # 不强制整表同页：允许在行与行之间分页，由 cantSplit 保证单行不被截断
    return tbl


