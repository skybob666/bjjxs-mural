def set_bold(el):
    for r in el.findall(qn("w:r")):
        rPr = r.find(qn("w:rPr"))
        if rPr is None:
            rPr = r.makeelement(qn("w:rPr"), {})
            r.insert(0, rPr)
        if rPr.find(qn("w:b")) is None:
            rPr.append(rPr.makeelement(qn("w:b"), {}))
    pPr = el.find(qn("w:pPr"))
    if pPr is not None:
        rPr = pPr.find(qn("w:rPr"))
        if rPr is not None and rPr.find(qn("w:b")) is None:
            rPr.append(rPr.makeelement(qn("w:b"), {}))


def set_page_break_before(el):
    """一级标题另起一页，避免章标题落在页脚只剩一行正文。"""
    pPr = el.find(qn("w:pPr"))
    if pPr is None:
        return
    node = pPr.find(qn("w:pageBreakBefore"))
    if node is not None:
        node.set(qn("w:val"), "1")
        return
    node = pPr.makeelement(qn("w:pageBreakBefore"), {})
    keep = pPr.find(qn("w:keepNext"))
    if keep is not None:
        keep.addnext(node)
    else:
        pPr.insert(0, node)

def set_keep_next(el):
    """按 schema 顺序设置 w:keepNext，已有则改值，避免重复节点导致文档异常。"""
    pPr = el.find(qn("w:pPr"))
    if pPr is None:
        return
    keep = pPr.find(qn("w:keepNext"))
    if keep is not None:
        keep.set(qn("w:val"), "1")
        return
    node = pPr.makeelement(qn("w:keepNext"), {})
    pStyle = pPr.find(qn("w:pStyle"))
    if pStyle is not None:
        pStyle.addnext(node)
    else:
        pPr.insert(0, node)


def set_size(el, half_points):
    for r in el.findall(qn("w:r")):
        rPr = r.find(qn("w:rPr"))
        if rPr is None:
            rPr = r.makeelement(qn("w:rPr"), {})
            r.insert(0, rPr)
        for tag in ("w:sz", "w:szCs"):
            old = rPr.find(qn(tag))
            if old is not None:
                rPr.remove(old)
            node = rPr.makeelement(qn(tag), {qn("w:val"): str(half_points)})
            rPr.append(node)


def emit(items):
    for it in items:
        kind = it[0]
        if kind == "pagebreak":
            p = body.makeelement(qn("w:p"), {})
            r = p.makeelement(qn("w:r"), {})
            br = p.makeelement(qn("w:br"), {qn("w:type"): "page"})
            r.append(br)
            p.append(r)
            sectPr.addprevious(p)
        elif kind == "cover":
            el = clone_para(EX["cover"], it[1])
            # 模板用分散对齐，短行会被强行拉伸；改为居中更整齐
            pPr = el.find(qn("w:pPr"))
            jc = pPr.find(qn("w:jc"))
            if jc is not None:
                jc.set(qn("w:val"), "center")
            sectPr.addprevious(el)
        elif kind in ("h1", "h2", "h3", "body", "caption"):
            el = clone_para(EX[kind], it[1])
            if kind == "h1":
                set_bold(el)  # 模板一级标题未加粗，与二级层级区分不足
                set_page_break_before(el)
            if kind in ("h1", "h2", "h3", "caption"):
                # 标题与表题不得单独留在页脚，必须与后文同页
                set_keep_next(el)
            sectPr.addprevious(el)
        elif kind == "coverline":
            el = clone_para(EX["caption"], it[1])
            set_size(el, 28)
            sectPr.addprevious(el)
        elif kind == "blank":
            for _ in range(it[1]):
                sectPr.addprevious(clone_para(EX["body"], ""))
        elif kind == "table":
            sectPr.addprevious(build_table(EX["table"], it[1], W))


